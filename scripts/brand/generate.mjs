import { composeOnSquare, encodeIco, solidSquare, svgToPng } from './raster.mjs';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const at = (...parts) => join(repoRoot, ...parts);
const ELECTRON_ICONS = at('packages/electron/resources/icons');
const CANARY_ICONS = at('packages/electron/resources/icons-canary');
const WEB_PUBLIC = at('packages/web/public');
const VSCODE_ASSETS = at('packages/vscode/assets');
const ANDROID_RES = at('packages/mobile/android/app/src/main/res');
const MOBILE_ASSETS = at('packages/mobile/assets');
const WIDGET_ASSETS = at('packages/mobile/ios/App/OpenChamberWidget/Assets.xcassets');
const TRANSPARENT = { r: 0, g: 0, b: 0, alpha: 0 };
const TILE = '#F9FCFF';
const INLINE_LOGO_FILES = [
  'packages/web/index.html', 'packages/electron/early-startup.mjs',
  'packages/vscode/src/webviewHtml.ts', 'packages/web/server/lib/opencode/static-routes-runtime.js',
];

const replaceMarked = (source, file) => {
  const startMark = '<!-- brand:flat-logo:start -->';
  const endMark = '<!-- brand:flat-logo:end -->';
  const start = source.indexOf(startMark);
  const end = source.indexOf(endMark);
  if (start < 0 || end < start) throw new Error(`${file}: missing brand logo region`);
  return source.slice(0, start + startMark.length) + flatLogoInner() + source.slice(end);
};

const notificationVector = () => `<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="32" android:viewportHeight="32">
    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="${GLYPH_PATHS.rear}" />
    <path android:fillColor="#FFFFFFFF" android:pathData="${GLYPH_PATHS.front}" />
</vector>
`;

const controlCenterSymbol = () => {
  const template = readFileSync(at('scripts/brand/symbol-template.svg'), 'utf8');
  const artwork = ['Ultralight', 'Regular', 'Black'].map((weight, column) => {
    const paths = Object.values(GLYPH_PATHS).map((path) => {
      let coordinate = 0;
      const scaled = path.replace(/-?\d+(?:\.\d+)?/g, (value) => {
        const offset = coordinate++ % 2 === 0 ? 233 + column * 200 : 79;
        return Number((Number(value) * 2 + offset).toFixed(4));
      });
      return `<path fill-rule="evenodd" d="${scaled}"/>`;
    }).join('');
    return `<g id="${weight}-S">${paths}</g>`;
  }).join('\n');
  return template.replace('<!-- brand:symbol -->', artwork);
};

const textOutputs = () => {
  const files = new Map([
    [join(ELECTRON_ICONS, 'AppIcon.icon/icon.json'), JSON.stringify(appIconDocument(), null, 2) + '\n'],
    [join(CANARY_ICONS, 'AppIcon.icon/icon.json'), JSON.stringify(appIconDocument({ canary: true }), null, 2) + '\n'],
    [join(ELECTRON_ICONS, 'icon-win.svg'), appIconSvg()],
    [join(ELECTRON_ICONS, 'app-icon.svg'), appIconSvg()],
    [join(ELECTRON_ICONS, 'dev-icon-win.svg'), appIconSvg({ tape: true })],
    [join(ELECTRON_ICONS, 'tray/tray-glyph.svg'), glyphSvg({ color: '#000000', zoom: MENU_BAR_GLYPH_ZOOM })],
    [join(WEB_PUBLIC, 'favicon.svg'), flatLogoSvg({ size: 32 })],
    [join(WEB_PUBLIC, 'apple-touch-icon.svg'), appIconSvg({ size: 180 })],
    [join(WEB_PUBLIC, 'logo-dark-512x512.svg'), flatLogoSvg()],
    [join(WEB_PUBLIC, 'logo-light-512x512.svg'), flatLogoSvg()],
    [at('docs/references/badges/openchamber-logo-dark.svg'), flatLogoSvg({ size: 100 })],
    [at('docs/references/badges/openchamber-logo-light.svg'), flatLogoSvg({ size: 100 })],
    [join(VSCODE_ASSETS, 'icon.svg'), glyphSvg({ size: 24 })],
    [join(VSCODE_ASSETS, 'icon-titlebar.svg'), glyphSvg({ size: 24, color: '#73C991' })],
    [join(VSCODE_ASSETS, 'icon-scm-titlebar.svg'), glyphSvg({ size: 24, color: '#C5C5C5' })],
    [join(ANDROID_RES, 'drawable/ic_stat_notify.xml'), notificationVector()],
    [join(ANDROID_RES, 'values/ic_launcher_background.xml'), `<?xml version="1.0" encoding="utf-8"?>\n<resources><color name="ic_launcher_background">${TILE}</color></resources>\n`],
    [at('packages/ui/src/components/ui/openChamberLogoArt.ts'), `// Generated by scripts/brand/generate.mjs. Do not edit.\nexport const OPEN_CHAMBER_LOGO_SRC = ${JSON.stringify('data:image/svg+xml,' + encodeURIComponent(flatLogoSvg()))};\nexport const LOGO_PANEL_REST = ${LOGO_PANEL_REST};\n`],
    [join(WIDGET_ASSETS, 'BrandLogo.imageset/Contents.json'), JSON.stringify({ images: [{ filename: 'logo.png', idiom: 'universal' }], info: { author: 'xcode', version: 1 } }, null, 2) + '\n'],
    [join(WIDGET_ASSETS, 'OCLogoSymbol.symbolset/oclogo-symbol.svg'), controlCenterSymbol()],
  ]);
  for (const file of INLINE_LOGO_FILES) files.set(at(file), replaceMarked(readFileSync(at(file), 'utf8'), file));
  return files;
};

const DENSITIES = { ldpi: 0.75, mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
const imageOutputs = async () => {
  const images = new Map();
  const put = (path, buffer) => images.set(path, buffer);
  for (const [name, art] of Object.entries(appIconLayerSvgs())) {
    const png = await svgToPng(art, 1024);
    put(join(ELECTRON_ICONS, 'AppIcon.icon/Assets', name), png);
    put(join(CANARY_ICONS, 'AppIcon.icon/Assets', name), png);
  }
  const icon = appIconSvg();
  const ico = (tape) => Promise.all([16, 20, 24, 32, 40, 48, 64, 128, 256].map(async (size) => ({ size, png: await svgToPng(appIconSvg({ tape }), size) })));
  put(join(ELECTRON_ICONS, 'icon.png'), await svgToPng(icon, 1024));
  put(join(ELECTRON_ICONS, 'app-icon.png'), await svgToPng(icon, 512));
  put(join(ELECTRON_ICONS, 'icon.ico'), encodeIco(await ico(false)));
  put(join(ELECTRON_ICONS, 'dev-icon.ico'), encodeIco(await ico(true)));

  const tray = async (name, options) => {
    for (const size of [18, 36]) put(
      join(ELECTRON_ICONS, 'tray', `trayTemplate-${name}${size === 36 ? '@2x' : ''}.png`),
      await svgToPng(glyphSvg({ color: '#000000', zoom: MENU_BAR_GLYPH_ZOOM, ...options }), size),
    );
  };
  await tray('idle', {});
  await tray('unseen', { rearOpacity: GLYPH_UNSEEN_OPACITY });
  for (const frame of [0, 3, 6, 9, 12, 15]) await tray(`breath-${String(frame).padStart(2, '0')}`, glyphBreathOpacity(frame));

  for (const size of [16, 32, 64]) put(join(WEB_PUBLIC, size === 64 ? 'favicon.png' : `favicon-${size}.png`), await svgToPng(flatLogoSvg(), size));
  for (const size of [120, 152, 167, 180]) put(join(WEB_PUBLIC, `apple-touch-icon-${size}x${size}.png`), await svgToPng(icon, size));
  put(join(WEB_PUBLIC, 'apple-touch-icon.png'), await svgToPng(icon, 180));
  for (const size of [192, 512]) {
    put(join(WEB_PUBLIC, `pwa-${size}.png`), await svgToPng(icon, size));
    put(join(WEB_PUBLIC, `pwa-maskable-${size}.png`), await composeOnSquare({ png: await svgToPng(flatLogoSvg(), size), size, background: TILE, inset: Math.round(size * 0.22) }));
  }
  for (const scheme of ['dark', 'light']) put(join(WEB_PUBLIC, `logo-${scheme}-192x192.png`), await svgToPng(flatLogoSvg(), 192));
  put(at('docs/references/badges/openchamber-logo-dark.png'), await svgToPng(flatLogoSvg(), 512));
  put(join(VSCODE_ASSETS, 'app-icon.png'), await svgToPng(icon, 512));

  for (const [density, scale] of Object.entries(DENSITIES)) {
    const dir = join(ANDROID_RES, `mipmap-${density}`);
    const size = Math.round(48 * scale);
    const foreground = await composeOnSquare({ png: await svgToPng(flatLogoSvg(), size), size, background: TRANSPARENT, inset: Math.round(size * 0.18) });
    put(join(dir, 'ic_launcher_background.png'), await solidSquare(size, TILE));
    put(join(dir, 'ic_launcher_foreground.png'), foreground);
    put(join(dir, 'ic_launcher.png'), await svgToPng(icon, size));
    put(join(dir, 'ic_launcher_round.png'), await composeOnSquare({ png: foreground, size, background: TILE, round: 'circle' }));
    if (density !== 'ldpi') {
      const themed = Math.round(108 * scale);
      put(join(dir, 'ic_launcher_monochrome.png'), await composeOnSquare({ png: await svgToPng(glyphSvg({ color: '#FFFFFF' }), themed), size: themed, background: TRANSPARENT, inset: Math.round(themed * 0.2) }));
    }
  }
  put(join(MOBILE_ASSETS, 'icon-only.png'), await svgToPng(icon, 1024));
  put(join(MOBILE_ASSETS, 'icon-foreground.png'), await composeOnSquare({ png: await svgToPng(flatLogoSvg(), 1024), size: 1024, background: TRANSPARENT, inset: 184 }));
  put(join(MOBILE_ASSETS, 'icon-background.png'), await solidSquare(1024, TILE));
  put(join(WIDGET_ASSETS, 'BrandLogo.imageset/logo.png'), await svgToPng(flatLogoSvg(), 512));
  return images;
};

const writeFile = (path, data) => { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, data); };
const cleanLayers = (iconsDir, keep = []) => {
  const assetsDir = join(iconsDir, 'AppIcon.icon/Assets');
  const layers = new Set([...Object.keys(appIconLayerSvgs()), ...keep]);
  if (existsSync(assetsDir)) for (const name of readdirSync(assetsDir)) if (!layers.has(name)) rmSync(join(assetsDir, name));
};

const macDevDockIcon = async (ictool) => {
  const tmp = mkdtempSync(join(tmpdir(), 'openchamber-dev-icon-'));
  try {
    const rendered = join(tmp, 'icon.png');
    execFileSync(ictool, [join(ELECTRON_ICONS, 'AppIcon.icon'), '--export-image', '--output-file', rendered, '--platform', 'macOS', '--rendition', 'Default', '--width', '1024', '--height', '1024', '--scale', '1']);
    const icon = await composeOnSquare({ png: readFileSync(rendered), size: 1024, background: TRANSPARENT, inset: 100 });
    const tape = await sharp(await svgToPng(devTapeSvg(), 1024)).composite([{ input: icon, blend: 'dest-in' }]).png().toBuffer();
    return sharp(icon).composite([{ input: tape }]).png().toBuffer();
  } finally { rmSync(tmp, { recursive: true, force: true }); }
};

const generate = async () => {
  cleanLayers(ELECTRON_ICONS);
  cleanLayers(CANARY_ICONS, ['canary-glyph.png']);
  for (const [path, text] of textOutputs()) writeFile(path, text);
  for (const [path, buffer] of await imageOutputs()) writeFile(path, buffer);
  for (const [path, buffer] of await canaryImageOutputs({ iconsDir: CANARY_ICONS, releaseIconsDir: ELECTRON_ICONS })) writeFile(path, buffer);
  execFileSync('bun', ['run', at('scripts/generate-icon-sprite.mjs')], { stdio: 'inherit' });
  if (process.platform === 'darwin') {
    const developerDir = process.env.DEVELOPER_DIR || execFileSync('xcode-select', ['-p'], { encoding: 'utf8' }).trim();
    const ictool = resolve(developerDir, '../Applications/Icon Composer.app/Contents/Executables/ictool');
    for (const dir of [ELECTRON_ICONS, CANARY_ICONS]) execFileSync('node', [at('packages/electron/scripts/generate-macos-icon-assets.cjs'), dir], { stdio: 'inherit' });
    writeFile(join(ELECTRON_ICONS, 'dev-icon.png'), await macDevDockIcon(ictool));
  }
  console.log('Wrote brand assets.');
};

const check = () => {
  const stale = [...textOutputs()].filter(([path, text]) => !existsSync(path) || readFileSync(path, 'utf8') !== text);
  if (stale.length) throw new Error(`Out of date, run brand:generate: ${stale.map(([path]) => relative(repoRoot, path)).join(', ')}`);
  console.log('Brand assets are up to date.');
};
export { textOutputs };
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) check();
  else await generate();
}
