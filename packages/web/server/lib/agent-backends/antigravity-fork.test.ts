test('forked steering records retain the identities used by subsequent projection', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'antigravity-steering-fork-'));
  t.after(() => fs.rm(directory, { recursive: true }));
  const storage = createConversationStorage(directory);
  t.after(() => storage.close());
  const history = createAntigravityHistoryFixture(storage);
  const source: StoredConversation = { id: 'source', nativeID: 'native', directory, title: 'Source', created: 1, updated: 4, draft: false, config: [], forms: [], turns: [] };
  history.save(source, { id: 'user', assistantID: 'assistant', modelID: 'model', text: 'Files', created: 1, completed: 4, files: [],
    updates: [{ sessionUpdate: 'agent_thought_chunk', content: { type: 'text', text: 'Before' } }, { sessionUpdate: 'agent_message_chunk', content: { type: 'text', text: 'After' } }],
    followups: [{ id: 'steer', text: 'Browser too', files: [], created: 2, updateIndex: 1, toolCallCount: 0 }] });
  const original = storage.message(source.id, 'assistant');
  assert.ok(original);
  storage.saveMessages([{ ...original, parts: [...original.parts, { id: 'failed_diff', messageID: 'assistant', sessionID: source.id, type: 'tool', tool: 'file_edit', callID: 'file_call', state: { status: 'error', input: {}, error: 'Capture failed', metadata: { openchamberTurnDiff: { error: 'Capture failed' } }, time: { start: 1, end: 2 } } }] }]);
  copyAntigravityHistory(storage, source.id, 'fork', '');
  const records = history.messages('fork', { order: 'asc' }).items;
  const [first, , steering, reply] = records;
  assert.ok(first && steering && reply);
  const turn = history.turn('fork', first.info.id);
  assert.ok(turn);
  assert.deepEqual(records.map(record => record.info.role), ['user', 'assistant', 'user', 'assistant']);
  assert.equal(records[1]?.parts[0]?.type === 'reasoning' && records[1].parts[0].text, 'Before');
  const failed = records[1]?.parts.find(part => part.type === 'tool');
  assert.deepEqual(failed?.type === 'tool' && failed.state.status === 'error' && failed.state.metadata?.openchamberTurnDiff, { error: 'Capture failed' });
  assert.equal(reply.parts[0]?.type === 'text' && reply.parts[0].text, 'After');
  assert.equal(reply.info.id, `${steering.info.id}_assistant`);
  assert.equal(records.some(record => ['user', 'assistant', 'steer', 'steer_assistant'].includes(record.info.id)), false);
});

test('native forks copy history and file diffs with independent identities and leave a running parent active', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'antigravity-fork-'));
  t.after(() => fs.rm(directory, { recursive: true }));
  const storage = createConversationStorage(directory);
  const history = createAntigravityHistoryFixture(storage);
  const source: StoredConversation = { id: 'ses_ag_parent', nativeID: randomUUID(), directory, title: 'Parent', created: 1, updated: 2, draft: false, config: [], metadata: { pinned: true }, forms: [], turns: [] };
  for (let index = 0; index < 2; index++) history.save(source, {
    id: `user_${index}`, assistantID: `assistant_${index}`, modelID: 'fixture', text: `Prompt ${index}`, files: [], created: index, completed: index + 1, followups: [],
    updates: [{ sessionUpdate: 'agent_message_chunk', content: { type: 'text', text: `Answer ${index}` } }],
    fileDiff: { turnID: `user_${index}`, files: [{ file: 'test.txt', status: 'modified' }] },
    toolCalls: [{ id: `call_${index}`, callID: `mcp_${index}`, namespace: 'file', name: 'edit', input: {}, started: index, completed: index + 1, updateIndex: 0, result: { content: [{ type: 'text', text: 'Edited' }, { type: 'image', data: 'AA==', mimeType: 'image/png' }] } }],
  });
  storage.saveDiff({ version: 1, sessionID: source.id, turnID: 'user_0', files: [{ file: 'test.txt', status: 'modified', patch: '-before\n+after' }] });
  const nativeFolder = path.join(directory, 'agent-backends', 'antigravity', 'profile', 'antigravity-acp', 'conversations');
  await fs.mkdir(nativeFolder, { recursive: true });
  const native = new DatabaseSync(path.join(nativeFolder, `${source.nativeID}.db`));
  t.after(() => native.close());
  native.exec(`CREATE TABLE trajectory_meta (trajectory_id TEXT, cascade_id TEXT);
    CREATE TABLE steps (idx INTEGER PRIMARY KEY, step_type INTEGER, metadata BLOB, step_payload BLOB);
    CREATE TABLE gen_metadata (idx INTEGER PRIMARY KEY, data BLOB);
    CREATE TABLE executor_metadata (idx INTEGER PRIMARY KEY, data BLOB);
    CREATE TABLE parent_references (idx INTEGER PRIMARY KEY, data BLOB);
    CREATE TABLE trajectory_metadata_blob (id TEXT, data BLOB);
    CREATE TABLE battle_mode_infos (idx INTEGER PRIMARY KEY, data BLOB);`);
  const trajectoryID = randomUUID();
  native.prepare('INSERT INTO trajectory_meta VALUES (?, ?)').run(trajectoryID, source.nativeID);
  const step = (index: number) => {
    const metadata = Uint8Array.from([162, 1, 2, 24, index]);
    native.prepare('INSERT INTO steps VALUES (?, 14, ?, ?)').run(index * 2, metadata, Buffer.from(`${trajectoryID}:${source.nativeID}`));
    native.prepare('INSERT INTO steps VALUES (?, 15, ?, ?)').run(index * 2 + 1, metadata, Buffer.from('Answer'));
    native.prepare('INSERT INTO gen_metadata VALUES (?, ?)').run(index, new Uint8Array());
  };
  step(0); step(1);
  const inherited: Array<[string, string | undefined]> = [];
  const forks: string[] = [];
  let streamed = () => {};
  const runtime = createConversationRuntime(storage);
  const backend = createAntigravityBackend({ runtime, storage, dataDir: directory, turnDiffs: { begin: async () => {}, finish: async () => {}, remove: async () => {} },
    environment: () => process.env, mcpServers: () => [], reassignSession: () => {}, initializeSession: async (id, _folder, parent) => { inherited.push([id, parent?.id]); }, readInstructions: async () => [],
    publish: event => {
      if (event.type === 'update' && event.update.sessionUpdate === 'agent_message_chunk') streamed();
      if (event.type === 'forked') { forks.push(event.session.id); assert.deepEqual(antigravityEvents(event).map(item => item.type), ['session.created', 'session.forked']); }
    }, publishForm: () => {} });
  t.after(async () => { await backend.close(); storage.close(); });
  await backend.ready;
  const fork = await backend.fork(source.id);
  assert.notEqual(fork.nativeID, source.nativeID);
  assert.deepEqual(fork.metadata, source.metadata);
  assert.deepEqual(inherited, [[fork.id, source.id]]);
  const copied = (await backend.messages(fork.id, { order: 'asc' })).items;
  assert.equal(copied.length, 4);
  assert.ok(copied.every(item => item.info.sessionID === fork.id && !['user_0', 'assistant_0', 'user_1', 'assistant_1'].includes(item.info.id)));
  const [user, assistant] = copied;
  assert.ok(user && assistant);
  const first = user.info.id;
  assert.equal(storage.diff(fork.id, first)?.files?.[0]?.patch, '-before\n+after');
  assert.equal((await backend.turn(fork.id, first))?.assistantID, assistant.info.id);
  const tool = assistant.parts.find(part => part.type === 'tool');
  assert.deepEqual(tool?.state.status === 'completed' && tool.state.metadata?.openchamberTurnDiff, { turnID: first, files: [{ file: 'test.txt', status: 'modified' }] });
  assert.ok(copied.flatMap(item => item.parts).every(part => part.sessionID === fork.id));
  const copy = new DatabaseSync(path.join(nativeFolder, `${fork.nativeID}.db`));
  assert.equal(copy.prepare('SELECT cascade_id FROM trajectory_meta').get()?.cascade_id, fork.nativeID);
  assert.notEqual(copy.prepare('SELECT trajectory_id FROM trajectory_meta').get()?.trajectory_id, trajectoryID);
  const firstStep = copy.prepare('SELECT step_payload FROM steps WHERE idx = 0').get();
  assert.ok(firstStep?.step_payload instanceof Uint8Array);
  assert.ok(Buffer.from(firstStep.step_payload).includes(Buffer.from(fork.nativeID)));
  copy.close();
  const cut = await backend.fork(source.id, 'user_1');
  assert.equal((await backend.messages(cut.id, {})).items.length, 2);
  assert.equal((await backend.messages(source.id, {})).items.length, 4);
  const executable = path.join(directory, 'agy');
  const fixture = fileURLToPath(new URL('./antigravity.fixture.mjs', import.meta.url));
  const quote = (value: string) => `'${value.replaceAll("'", "'\\''")}'`;
  await fs.writeFile(executable, `#!/bin/sh\nexec ${quote(process.execPath)} ${quote(fixture)} "$@"\n`, { mode: 0o700 });
  await backend.configure({ binary: executable });
  step(2);
  const update = new Promise<void>(resolve => { streamed = resolve; });
  const quoteMetadata = { openchamberContext: { kind: 'chat-quote', quote: 'Quoted source', text: 'About this quote' } };
  await backend.send(source.id, { id: 'running', text: 'working', files: [], context: [{ id: 'quote', text: 'Quoted source', metadata: quoteMetadata }] });
  await update;
  runtime.tool(source.id, { id: 'active_call', callID: 'active_mcp', namespace: 'file', name: 'edit', input: {}, started: 3, completed: 4, updateIndex: 1, result: { content: [{ type: 'text', text: 'Edited during active turn' }] } }, directory);
  const parentHistory = (await backend.messages(source.id, { order: 'asc' })).items;
  const btw = await backend.fork(source.id);
  assert.equal(backend.statuses()[source.id]?.type, 'busy');
  const inheritedHistory = (await backend.messages(btw.id, { order: 'asc' })).items;
  assert.equal(inheritedHistory.length, 7);
  const inheritedQuote = inheritedHistory.at(-3)?.info;
  assert.equal(inheritedQuote?.role, 'synthetic');
  assert.notEqual(inheritedQuote?.id, 'quote');
  assert.deepEqual(inheritedQuote?.metadata, quoteMetadata);
  const inheritedInput = inheritedHistory.at(-2);
  assert.ok(inheritedInput);
  const inheritedTurn = await backend.turn(btw.id, inheritedInput.info.id);
  assert.equal(inheritedTurn?.inputContext?.[0]?.id, inheritedQuote?.id);
  assert.equal(inheritedTurn?.inputContext?.[0]?.text, 'Quoted source');
  assert.deepEqual(inheritedHistory.at(-2)?.parts.map(part => part.type === 'text' && part.text), ['working']);
  const activeReply = inheritedHistory.at(-1);
  assert.ok(activeReply?.parts.some(part => part.type === 'text' && part.text === 'Quoted sourceworking'));
  assert.ok(activeReply?.parts.some(part => part.type === 'tool' && part.state.status === 'completed' && part.state.output === 'Edited during active turn'));
  const activeCopy = new DatabaseSync(path.join(nativeFolder, `${btw.nativeID}.db`));
  assert.equal(activeCopy.prepare('SELECT COUNT(*) AS count FROM steps').get()?.count, 6);
  activeCopy.close();
  await backend.send(btw.id, { id: 'btw_question', text: 'Side question', files: [], context: [] });
  await backend.wait(btw.id, AbortSignal.timeout(10_000));
  assert.equal((await backend.messages(btw.id, {})).items.length, 9);
  assert.deepEqual((await backend.messages(source.id, { order: 'asc' })).items, parentHistory);
  assert.equal(backend.statuses()[source.id]?.type, 'busy');
  assert.deepEqual(forks, [fork.id, cut.id, btw.id]);
  step(3);
  await backend.send(source.id, { id: 'steering', text: 'Follow-up prompt', files: [], context: [{ id: 'followup_quote', text: 'Follow-up quote' }] });
  await backend.wait(source.id, AbortSignal.timeout(10_000));
  const cutFollowup = await backend.fork(source.id, 'steering');
  const retained = (await backend.messages(cutFollowup.id, { order: 'asc' })).items;
  assert.equal(retained.length, 7);
  assert.equal(retained.at(-1)?.parts.some(part => part.type === 'text' && part.text === 'Quoted sourceworking'), true);
  assert.equal(retained.some(record => record.info.role === 'synthetic' && record.info.text === 'Follow-up quote'), false);
  await backend.stageRevert(source.id, 'steering');
  await backend.commitRevert(source.id);
  const original = await backend.turn(source.id, 'running');
  assert.ok(original);
  assert.deepEqual(original.followups, []);
  assert.deepEqual(original.updates.filter(item => item.sessionUpdate === 'agent_message_chunk').map(item => item.content), [{ type: 'text', text: 'Quoted sourceworking' }]);
  assert.equal((await backend.messages(source.id, {})).items.flatMap(record => record.parts).some(part => part.type === 'tool' && part.state.status === 'completed' && part.state.output === 'Edited during active turn'), true);
  assert.equal((await backend.messages(source.id, {})).items.length, 7);
  assert.equal(native.prepare('SELECT COUNT(*) AS count FROM steps').get()?.count, 6);
  await backend.send(source.id, { id: 'edited', text: 'Edited follow-up', files: [], context: [] });
  await backend.wait(source.id, AbortSignal.timeout(10_000));
  assert.equal((await backend.messages(source.id, {})).items.length, 9);
});
