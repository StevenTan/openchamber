import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import type { MessageRecord } from '@openchamber/sdk/conversations/http';
import { createConversationStorage } from './conversation-storage.js';
import { createConversationRuntime } from './conversation-runtime.js';
import { shellMessageRecords } from '../opencode/message-shells.js';

test('OpenCode display history pages snapshots, retains live output and reopens from disk', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'opencode-history-'));
  t.after(() => fs.rm(directory, { recursive: true }));
  const id = 'ses_history';
  const user: MessageRecord = { info: { id: 'msg_z', sessionID: id, role: 'user', time: { created: 10 } }, parts: [] };
  const assistant: MessageRecord = { info: { id: 'msg_a', sessionID: id, role: 'assistant', time: { created: 2 }, providerID: 'codex', modelID: 'gpt', agent: 'build' }, parts: [] };
  let history = createConversationRuntime(createConversationStorage(directory));
  t.after(() => history.close());
  let pages = 0;
  await history.importSession(id, async input => {
    pages++;
    assert.equal(input.order, 'asc');
    assert.equal(input.limit, 100);
    if (!input.cursor) return { items: [user], cursor: { next: 'native-next' } };
    history.record({ type: 'message.updated', properties: { info: assistant.info } });
    history.record({ type: 'message.part.updated', properties: { sessionID: id, part: { id: 'text', sessionID: id, messageID: assistant.info.id, type: 'text', text: '' } } });
    history.record({ type: 'message.part.delta', properties: { sessionID: id, messageID: assistant.info.id, partID: 'text', field: 'text', delta: 'live reply' } });
    return { items: [assistant], cursor: {} };
  });
  assert.equal(pages, 2);
  await history.importSession(id, async () => { throw new Error('An imported page is read from OpenChamber'); });
  const first = history.messages(id, { limit: 1 });
  assert.equal(first.items[0]?.info.id, assistant.info.id);
  assert.equal(first.items[0]?.parts[0]?.type === 'text' && first.items[0].parts[0].text, 'live reply');
  assert.deepEqual(history.messages(id, { limit: 1, cursor: first.cursor.next }).items, [user]);
  assert.deepEqual(history.messages(id, { order: 'asc' }).items.map(item => item.info.id), [user.info.id, assistant.info.id]);
  const tool = { id: 'tool', sessionID: id, messageID: assistant.info.id, type: 'tool' as const, callID: 'call', tool: 'exec_command', state: { status: 'pending' as const, input: {}, raw: '' } };
  history.record({ type: 'message.part.updated', properties: { sessionID: id, part: tool } });
  history.record({ type: 'message.part.delta', properties: { sessionID: id, messageID: assistant.info.id, partID: tool.id, field: 'raw', delta: '{"cmd":"pwd"}' } });
  const pending = history.message(id, assistant.info.id)?.parts[1];
  assert.equal(pending?.type === 'tool' && pending.state.status === 'pending' && pending.state.raw, '{"cmd":"pwd"}');
  const transition = (value: import('@openchamber/sdk/conversations/events').ToolTransition) => history.record({ type: 'message.tool.transition', properties: { sessionID: id, messageID: assistant.info.id, partID: tool.id, transition: value } });
  transition({ kind: 'called', input: { cmd: 'pwd' }, executed: true, start: 3 });
  transition({ kind: 'success', output: '/workspace', metadata: { title: 'pwd' }, executed: true, end: 4 });
  const exact = history.message(id, assistant.info.id);
  assert.ok(exact);
  const full = exact.parts[1];
  assert.equal(full?.type === 'tool' && full.state.status === 'completed' && full.state.output, '/workspace');
  const shell = shellMessageRecords([exact])[0]?.parts[1];
  assert.equal(shell?.type === 'tool' && shell.state.status === 'completed' && shell.state.output, '');
  assert.deepEqual(shell?.type === 'tool' && shell.state.status === 'completed' && shell.state.metadata?.openchamberContentShell, { chars: 10 });
  assert.deepEqual(history.message(id, assistant.info.id), exact);
  history.close();
  history = createConversationRuntime(createConversationStorage(directory));
  assert.deepEqual(history.message(id, assistant.info.id), exact);
  await assert.rejects(history.importSession(id, async () => { throw new Error('OpenCode unavailable'); }), /OpenCode unavailable/);
  assert.deepEqual(history.message(id, assistant.info.id), exact);
  await history.importSession(id, async () => ({ items: [user], cursor: {} }));
  assert.deepEqual(history.messages(id, {}).items, [user]);
  history.remove(id);
  assert.deepEqual(history.messages(id, {}).items, []);
});

test('display history admits queued messages, compaction and revert in event order', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'opencode-history-events-'));
  t.after(() => fs.rm(directory, { recursive: true }));
  const history = createConversationRuntime(createConversationStorage(directory));
  t.after(() => history.close());
  const id = 'ses_events';
  history.record({ type: 'message.updated', properties: { info: { id: 'queued', sessionID: id, role: 'synthetic', time: { created: 1 }, text: 'follow-up', pending: true } } });
  history.record({ type: 'message.updated', properties: { info: { id: 'reply', sessionID: id, role: 'user', time: { created: 2 } } } });
  history.record({ type: 'message.patched', properties: { sessionID: id, messageID: 'queued', patch: { time: { created: 3 } } } });
  assert.deepEqual(history.messages(id, { order: 'asc' }).items.map(item => item.info.id), ['reply', 'queued']);
  history.record({ type: 'message.updated', properties: { info: { id: 'compacting', sessionID: id, role: 'compaction', time: { created: 4 }, status: 'running', reason: 'auto', summary: '' } } });
  history.record({ type: 'message.compaction.delta', properties: { sessionID: id, delta: 'summary' } });
  const running = history.message(id, 'compacting');
  assert.equal(running?.info.role === 'compaction' && running.info.summary, 'summary');
  history.record({ type: 'message.updated', properties: { info: { id: 'completed-compaction', sessionID: id, role: 'compaction', time: { created: 5 }, status: 'completed', reason: 'auto', summary: 'final summary' } } });
  const messages = history.messages(id, { order: 'asc' }).items;
  assert.equal(messages.length, 3);
  assert.equal(messages[2]?.info.id, 'compacting');
  assert.equal(messages[2]?.info.role === 'compaction' && messages[2].info.summary, 'final summary');
  history.record({ type: 'session.revert.committed', properties: { sessionID: id, to: 'queued' } });
  assert.deepEqual(history.messages(id, {}).items.map(item => item.info.id), ['reply']);
  history.record({ type: 'session.deleted', properties: { sessionID: id } });
  assert.deepEqual(history.messages(id, {}).items, []);
  history.record({ type: 'message.updated', properties: { info: { id: 'shell-message', sessionID: id, role: 'shell', time: { created: 6 }, shellID: 'shell-native', command: 'pwd', status: 'running' } } });
  const output = { output: '/workspace', cursor: 10, size: 10, truncated: false };
  history.record({ type: 'message.patched', properties: { sessionID: id, messageID: 'shell:shell-native', patch: { time: { completed: 7 }, shell: { status: 'exited', exit: 0, output } } } });
  const shell = history.message(id, 'shell-message');
  assert.deepEqual(shell?.info.role === 'shell' && shell.info.output, output);
  assert.equal(shell?.info.role === 'shell' && shell.info.time.completed, 7);
});

test('host tool results keep their message and position across OpenCode history imports', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'conversation-tools-'));
  t.after(() => fs.rm(directory, { recursive: true }));
  const history = createConversationRuntime(createConversationStorage(directory));
  t.after(() => history.close());
  const id = 'ses_tools';
  const assistant: MessageRecord = { info: { id: 'assistant', sessionID: id, role: 'assistant', providerID: 'codex', modelID: 'gpt', agent: 'build', time: { created: 1 } }, parts: [] };
  history.record({ type: 'message.updated', properties: { info: assistant.info } });
  history.tool(id, { id: 'host', callID: 'native', partID: 'native', messageID: 'assistant', namespace: 'file', name: 'edit', input: { path: 'code.txt' }, started: 2 }, directory);
  history.record({ type: 'message.updated', properties: { info: { ...assistant.info, id: 'after-steer', time: { created: 3 } } } });
  history.tool(id, { id: 'host', callID: 'native', partID: 'native', messageID: 'assistant', namespace: 'file', name: 'edit', input: { path: 'code.txt' }, started: 2, completed: 4, result: { content: [{ type: 'text', text: 'Edited' }] } }, directory);
  const stored = history.message(id, 'assistant');
  assert.equal(stored?.parts[0]?.type === 'tool' && stored.parts[0].state.status === 'completed' && stored.parts[0].state.output, 'Edited');
  const afterSteer = history.message(id, 'after-steer');
  assert.ok(afterSteer);
  assert.deepEqual(afterSteer.parts, []);
  await history.importSession(id, async () => ({ items: [{ ...assistant, parts: [{ id: 'native', type: 'tool', sessionID: id, messageID: 'assistant', callID: 'native', tool: 'file_edit', state: { status: 'running', input: {}, time: { start: 2 } } }] }, afterSteer], cursor: {} }));
  assert.deepEqual(history.message(id, 'assistant'), stored);
});
